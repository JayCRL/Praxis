export function seed(store) {
  let n = 0;
  for (const s of SEED) {
    const created = ago(s.days ?? 10, 5);
    const tags = JSON.stringify(s.tags ?? []);
    const tools = JSON.stringify(s.tools ?? []);
    // Spread the lessons across plausible contributing agents so the network
    // view has more than one voice in it.
    const contributors = AGENTS[s.taskType ?? 'general'] ?? ['lead'];
    const agent = s.agent && s.agent !== 'lead' ? s.agent : contributors[n % contributors.length];
    store.db.prepare('DELETE FROM lessons WHERE id = ?').run(s.id);
    store.db.prepare('DELETE FROM events WHERE lesson_id = ?').run(s.id);
    store.db
      .prepare(
        `INSERT INTO lessons (id, title, rule, context, symptom, cause, fix, tags, task_type, env, env_detail, tools,
           scope, agent, model, session, up, down, confirms, conflicts, verified, status, created_at, updated_at)
         VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?, 'active', ?, ?)`,
      )
      .run(
        s.id,
        s.title,
        s.rule,
        s.context ?? '',
        s.symptom ?? '',
        s.cause ?? '',
        s.fix ?? '',
        tags,
        s.taskType ?? 'general',
        s.env ?? 'any',
        s.envDetail ?? 'Windows 11 24H2 · Node 24 · pwsh 7.4',
        tools,
        s.scope ?? 'global',
        agent,
        s.model ?? 'deepseek-flash',
        `seed-${s.id.slice(-6)}`,
        s.up ?? 0,
        s.down ?? 0,
        s.confirms ?? 0,
        s.conflicts ?? 0,
        s.verified ?? 0,
        created,
        created,
      );
    store.reindex(s.id);
    store.logEvent(s.id, 'create', agent, '');
    n++;
  }
  return n;
}

const AGENTS = {
  coding: ['atlas', 'lead'],
  ops: ['kestrel', 'relay'],
  design: ['mira'],
  hardware: ['sol'],
  writing: ['quill'],
  general: ['lead', 'bob'],
};

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = process.env.PRAXIS_DB ?? fileURLToPath(new URL('../data/praxis.db', import.meta.url));
  const store = new Store(file);
  const n = seed(store);
  console.log(`seeded ${n} lessons -> ${file}`);
  store.close();
}
